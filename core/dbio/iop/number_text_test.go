package iop

import (
	"testing"

	"github.com/stretchr/testify/assert"
)

func TestNormalizeNumberText(t *testing.T) {
	tests := []struct{ in, out string }{
		{"3000", "3000"},
		{"1,234,567", "1234567"},
		{"-1,234,567.89", "-1234567.89"},
		{"1,234.5", "1234.5"},
		{"+12,345,678", "+12345678"},
		{"1,5", "1.5"},
		{"-1,5", "-1.5"},
		{"45,3828582763672", "45.3828582763672"},
		{"0,500", "0.500"},
		{"1234,567", "1234.567"},
		{"3,000", "3,000"},
		{"-3,000", "-3,000"},
		{"1.234,56", "1.234,56"},
		{"1,23,456", "1,23,456"},
		{"a,b", "a,b"},
		{",5", ",5"},
		{"1,", "1,"},
		{"1,234,", "1,234,"},
		{"1,234.", "1,234."},
		{"1,234.5a", "1,234.5a"},
		{"", ""},
	}
	for _, tt := range tests {
		assert.Equal(t, tt.out, normalizeNumberText(tt.in), tt.in)
	}
}
